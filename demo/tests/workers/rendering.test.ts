import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createTestHarness } from "wrangler";

for (const framework of ["hono", "express"] as const) {
  describe(`${framework} rendering Worker`, () => {
    const harness = createTestHarness({
      workers: [
        {
          config: {
            name: `rendering-${framework}`,
            main: `tests/fixtures/workers/rendering/${framework}.${framework === "hono" ? "tsx" : "ts"}`,
            compatibility_date: "2026-10-01",
            compatibility_flags:
              framework === "express" ? ["nodejs_compat"] : [],
          },
        },
      ],
    });
    beforeAll(() => harness.listen());
    afterAll(() => harness.close());
    it("returns the complete HTML document", async () => {
      const response = await harness.fetch("/pages/home");
      expect(response.status).toBe(200);
      expect(response.headers.get("content-type")).toContain("text/html");
      const html = await response.text();
      expect(html).toMatch(/^<!doctype html>/i);
      expect(html).toContain("<html");
      expect(html).toContain("<head>");
      expect(html).toContain("<body>");
      expect(html).toContain('href="../rendering/style.css"');
      expect(html).toContain('type="module"');
    });
    it("returns a standards-mode document for the second page", async () => {
      const response = await harness.fetch("/pages/second");
      expect(await response.text()).toMatch(/^<!doctype html>/i);
    });
    it("serves a script resource generated by the Worker", async () => {
      const page = await harness.fetch("/pages/generated");
      expect(await page.text()).toContain('src="../api/generated.js"');
      const script = await harness.fetch("/api/generated.js");
      expect(script.status).toBe(200);
      expect(script.headers.get("content-type")).toMatch(/javascript/);
      expect(await script.text()).toContain("Worker script ready");
    });
    if (framework === "express") {
      it("returns a bodyless 304 for an ETag revalidation", async () => {
        const initial = await harness.fetch("/pages/home");
        const etag = initial.headers.get("etag");
        expect(etag).toBeTruthy();
        const revalidated = await harness.fetch("/pages/home", {
          // Node fetch otherwise supplies no-cache for conditional requests,
          // which tells Express to return a full response rather than a 304.
          headers: { "if-none-match": etag!, "cache-control": "max-age=0" },
        });
        expect(revalidated.status).toBe(304);
        expect(await revalidated.text()).toBe("");
      });
    }
    it("escapes the GET form value in the rendered page", async () => {
      const response = await harness.fetch(
        `/pages/search?q=${encodeURIComponent("日本語 & <tag>")}`,
      );
      const html = await response.text();
      expect(html).toMatch(/^<!doctype html>/i);
      expect(html).toContain("日本語 &amp; &lt;tag&gt;");
      expect(html).not.toContain("<tag>");
    });
    it.each([301, 302, 303, 307, 308])(
      "POST → %i follows standard method/body rules",
      async (status) => {
        const body = new URLSearchParams([
          ["message", "日本語 & <tag>"],
          ["duplicate", "one"],
          ["duplicate", "two"],
        ]);
        const initial = await harness.fetch(`/api/redirect/${status}`, {
          method: "POST",
          body,
          redirect: "manual",
        });
        expect(initial.status).toBe(status);
        expect(initial.headers.get("location")).toBe(`../echo?via=${status}`);
        const response = await harness.fetch(`/api/redirect/${status}`, {
          method: "POST",
          body,
        });
        const value = (await response.json()) as {
          method: string;
          fields: unknown[];
        };
        expect(value.method).toBe(status >= 307 ? "POST" : "GET");
        expect(value.fields).toEqual(status >= 307 ? Array.from(body) : []);
      },
    );
    it("retains multipart file bytes", async () => {
      const body = new FormData();
      body.append(
        "upload",
        new Blob([new Uint8Array([0, 1, 128, 255])], {
          type: "application/octet-stream",
        }),
        "bytes.bin",
      );
      const encoded = new Response(body);
      const response = await harness.fetch("/api/echo", {
        method: "POST",
        headers: { "content-type": encoded.headers.get("content-type")! },
        body: new Uint8Array(await encoded.arrayBuffer()),
      });
      expect(await response.json()).toMatchObject({
        method: "POST",
        fields: [
          [
            "upload",
            {
              name: "bytes.bin",
              type: "application/octet-stream",
              bytes: [0, 1, 128, 255],
            },
          ],
        ],
      });
    });
  });
}
